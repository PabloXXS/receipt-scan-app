/// Назначение: источник чека (QR-код или фото для OCR).
///
/// Слой: domain
/// Фича: scan
/// Зависимости: нет.
/// Ключевые типы: ScanSource.
library;

/// Источник «сырого» чека. Значения совпадают со значением колонки `receipts.source`.
enum ScanSource {
  /// QR-код кассового чека (реализация — отдельный цикл).
  qr,

  /// Фотография чека (распознаётся воркером, OCR-fallback).
  ocr;

  /// Значение для колонки `receipts.source`.
  String get dbValue => name;
}
